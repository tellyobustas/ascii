export type RenderVectorTextOptions = {
  align?: "center" | "left" | "right";
  charHeight: number;
  charWidth: number;
  color: string;
  letterSpacing?: number;
  opacity?: number;
  text: string;
  x: number;
  y: number;
};

export function renderVectorText({
  align = "left",
  charHeight,
  charWidth,
  color,
  letterSpacing = charWidth * 0.28,
  opacity = 1,
  text,
  x,
  y,
}: RenderVectorTextOptions): string {
  const chars = Array.from(text.toUpperCase());
  const totalWidth = chars.length * (charWidth + letterSpacing) - letterSpacing;
  const startX =
    align === "right"
      ? x - totalWidth
      : align === "center"
        ? x - totalWidth / 2
        : x;
  const dotW = charWidth / 5;
  const dotH = charHeight / 7;
  const rects: string[] = [];

  for (let cIdx = 0; cIdx < chars.length; cIdx += 1) {
    const char = chars[cIdx];
    const pattern = PIXEL_FONT_5X7[char] ?? PIXEL_FONT_5X7[" "];
    if (!pattern) continue;
    const cx = startX + cIdx * (charWidth + letterSpacing);

    for (let row = 0; row < 7; row += 1) {
      let runStart = -1;
      for (let col = 0; col < 5; col += 1) {
        if (pattern[row][col] === "1") {
          if (runStart === -1) runStart = col;
        } else if (runStart !== -1) {
          const rx = (cx + runStart * dotW).toFixed(1);
          const ry = (y + row * dotH).toFixed(1);
          const rw = ((col - runStart) * dotW).toFixed(1);
          const rh = dotH.toFixed(1);
          rects.push(`<rect x="${rx}" y="${ry}" width="${rw}" height="${rh}"/>`);
          runStart = -1;
        }
      }
      if (runStart !== -1) {
        const rx = (cx + runStart * dotW).toFixed(1);
        const ry = (y + row * dotH).toFixed(1);
        const rw = ((5 - runStart) * dotW).toFixed(1);
        const rh = dotH.toFixed(1);
        rects.push(`<rect x="${rx}" y="${ry}" width="${rw}" height="${rh}"/>`);
      }
    }
  }

  return `<g fill="${color}" opacity="${opacity.toFixed(2)}">${rects.join("")}</g>`;
}
