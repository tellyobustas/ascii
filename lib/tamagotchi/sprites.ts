export function getPetSprite(
  stage: PetStage,
  mood: PetMood,
  eggWarmCount = 0,
): string[] {
  switch (stage) {
    case "EGG":
      if (eggWarmCount >= 5) return EGG_SPRITES.crack;
      if (eggWarmCount >= 2) return EGG_SPRITES.warm;
      return EGG_SPRITES.idle;
    case "NIBBLE":
      return NIBBLE_SPRITES[mood] ?? NIBBLE_SPRITES.NORMAL;
    case "SPARK":
      return SPARK_SPRITES[mood] ?? SPARK_SPRITES.NORMAL;
    case "IMP":
      return IMP_SPRITES[mood] ?? IMP_SPRITES.NORMAL;
    case "PROTO_DAEMON":
      return PROTO_DAEMON_SPRITES[mood] ?? PROTO_DAEMON_SPRITES.NORMAL;
    case "DAEMON_CORE":
      return DAEMON_CORE_SPRITES[mood] ?? DAEMON_CORE_SPRITES.NORMAL;
    case "CYBER_ARMOR":
      return CYBER_ARMOR_SPRITES[mood] ?? CYBER_ARMOR_SPRITES.NORMAL;
    case "NEO_OVERLORD":
      return NEO_OVERLORD_SPRITES[mood] ?? NEO_OVERLORD_SPRITES.NORMAL;
    case "OMEGA_DEITY":
      return OMEGA_DEITY_SPRITES[mood] ?? OMEGA_DEITY_SPRITES.NORMAL;
    default:
      return NIBBLE_SPRITES.NORMAL;
  }
}

export interface AccessoryOverlay {
  headGlyph: string | null;
  droneGlyph: string | null;
  bodyLeft: string | null;
  bodyRight: string | null;
}

export function getAccessoryOverlay(
  head: HeadAccessory,
  drone: DroneAccessory,
  body?: BodyAccessory,
): AccessoryOverlay {
  let headGlyph: string | null = null;
  if (head === "VISOR") headGlyph = "[ ═══ ]";
  if (head === "HALO") headGlyph = ".-~✦~-.";
  if (head === "HORNS") headGlyph = "//     \\\\";

  let droneGlyph: string | null = null;
  if (drone === "BIT") droneGlyph = "[01]";
  if (drone === "ORB") droneGlyph = "( ✦ )";
  if (drone === "MINI_DEMON") droneGlyph = "/\\^o^/\\";

  let bodyLeft: string | null = null;
  let bodyRight: string | null = null;
  if (body === "EXO_SPINE") {
    bodyLeft = ">══";
    bodyRight = "══<";
  } else if (body === "FORCE_FIELD") {
    bodyLeft = "{";
    bodyRight = "}";
  } else if (body === "TESLA_COILS") {
    bodyLeft = "╒⚡";
    bodyRight = "⚡╕";
  }

  return { headGlyph, droneGlyph, bodyLeft, bodyRight };
}
